# Generates src/ui/MainMenuDef.inc from upstream PowerEditor/src/Notepad_plus.rc (IDR_M30_MENU),
# so the Qt main menu has exactly the upstream structure and IDM_* command ids.
# Usage: tools/gen_mainmenu.py <upstream PowerEditor/src>/Notepad_plus.rc src/ui/MainMenuDef.inc

import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8', errors='replace').read().replace('\r', '')
lines = text.split('\n')

start = next(i for i, l in enumerate(lines) if l.strip() == 'IDR_M30_MENU MENU')
assert lines[start + 1].strip() == 'BEGIN'

def cstr(s):
    s = s.replace('""', '"')  # .rc escapes quotes by doubling
    out = ''
    for ch in s:
        if ch == '\\':
            out += '\\\\'
        elif ch == '"':
            out += '\\"'
        elif ord(ch) < 128:
            out += ch
        else:
            out += '\\u%04X' % ord(ch) if ord(ch) <= 0xFFFF else '\\U%08X' % ord(ch)
    return 'L"' + out + '"'

entries = []
depth = 0
i = start + 2
popupRe = re.compile(r'^\s*POPUP\s+"((?:[^"]|"")*)"')
itemRe = re.compile(r'^\s*MENUITEM\s+"((?:[^"]|"")*)"\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:,\s*(.*))?$')
while i < len(lines):
    l = lines[i].strip()
    i += 1
    if not l or l.startswith('//'):
        continue
    if l == 'BEGIN':
        depth += 1
        continue
    if l == 'END':
        if depth == 0:
            break
        depth -= 1
        entries.append(('NppMenuDef::PopupEnd', 'nullptr', '0', '0'))
        continue
    m = popupRe.match(lines[i - 1])
    if m:
        entries.append(('NppMenuDef::PopupBegin', cstr(m.group(1)), '0', '0'))
        continue
    if l.startswith('MENUITEM SEPARATOR'):
        entries.append(('NppMenuDef::Separator', 'nullptr', '0', '0'))
        continue
    m = itemRe.match(lines[i - 1])
    if m:
        flags = (m.group(3) or '').replace(' ', '')
        f = []
        if 'GRAYED' in flags: f.append('NppMenuDef::Grayed')
        if 'CHECKED' in flags: f.append('NppMenuDef::Checked')
        if 'HELP' in flags: f.append('NppMenuDef::RightAligned')
        entries.append(('NppMenuDef::Item', cstr(m.group(1)), m.group(2), '|'.join(f) or '0'))
        continue
    raise SystemExit('unparsed line %d: %s' % (i, l))

with open(dst, 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/gen_mainmenu.py from upstream Notepad_plus.rc (IDR_M30_MENU). Do not edit.\n')
    out.write('// %d entries\n' % len(entries))
    for kind, label, ident, flags in entries:
        out.write('\t{ %s, %s, %s, %s },\n' % (kind, label, ident, flags))
print('%d entries written to %s' % (len(entries), dst))
